-- =====================================================================
-- সংশোধিত এন্ট্রি একই মেমো নম্বর রাখতে পারবে
-- =====================================================================
-- মেমো নম্বর দুবার দেওয়া যায় না — এই নিয়মটা ঠিকই আছে। কিন্তু সংশোধনের
-- সময় মূল এন্ট্রিটা বাতিল হয়ে খাতায় থেকে যায়, আর তার নম্বরটা ধরে রাখে।
-- ফলে সংশোধিত এন্ট্রিটা ঐ একই মেমো নম্বরে বসতে গিয়ে আটকে যেত — অথচ
-- কাগজের মেমোটা তো একটাই, নম্বরও একটাই।
--
-- তাই নিয়মটা এখন থেকে চালু এন্ট্রির জন্য: বাতিল হয়ে যাওয়া এন্ট্রি আর
-- নম্বরটা আটকে রাখে না।
-- =====================================================================

DROP INDEX IF EXISTS public.invoices_memo_no_key;

CREATE UNIQUE INDEX IF NOT EXISTS invoices_memo_no_key
  ON public.invoices (lower(btrim(memo_no)))
  WHERE memo_no IS NOT NULL AND btrim(memo_no) <> '' AND reversed_at IS NULL;

-- ---------------------------------------------------------------------
-- যাচাই
-- ---------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_indexes
     WHERE schemaname = 'public' AND indexname = 'invoices_memo_no_key'
       AND indexdef LIKE '%reversed_at IS NULL%'
  ) THEN
    RAISE EXCEPTION 'মেমো নম্বরের নতুন নিয়মটা বসেনি';
  END IF;
END $$;
